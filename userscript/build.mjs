// Builds userscript/safescroll.user.js from the extension's own code, so the
// Safari version has the same filters, limits and settings screen.
// Usage: node userscript/build.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const ext = path.join(here, "..", "extension");
const read = (...p) => fs.readFileSync(path.join(...p), "utf8");
const manifest = JSON.parse(read(ext, "manifest.json"));
const safe = js => js.replace(/<\/script/gi, "<\\/script");

function inlinePage(file, extraHead = "", before = {}) {
  const dir = path.dirname(path.join(ext, file));
  let html = read(ext, file);
  html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (_, href) => `<style>${read(dir, href)}</style>`);
  html = html.replace(/<script src="([^"]+)"><\/script>/g, (_, src) =>
    `${before[src] || ""}<script>${safe(read(dir, src))}</script>`);
  return html.replace("<head>", `<head>${extraHead}`);
}

const settingsHtml = inlinePage("options/options.html",
  `<script>${safe(read(here, "settings-bridge.js"))}</script>`);
const blockedHtml = inlinePage("blocked/blocked.html", `<base target="_top">`,
  { "blocked.js": `<script>window.__safescrollParams = __PARAMS__;</script>` });

const matches = manifest.content_scripts[0].matches;
const version = `${manifest.version}.${new Date().toISOString().slice(0, 10).replace(/-/g, "")}`;
const raw = "https://github.com/physicstheory/socialmods/raw/HEAD/userscript/safescroll.user.js";
const header = [
  "// ==UserScript==",
  "// @name         SafeScroll",
  "// @namespace    https://github.com/physicstheory/socialmods",
  `// @version      ${version}`,
  "// @description  Age-based filters, For You limits and PIN-locked parent settings for TikTok, Instagram, Facebook, Threads and Snapchat in Safari.",
  ...matches.map(m => `// @match        ${m}`),
  "// @run-at       document-start",
  "// @inject-into  content",
  "// @noframes",
  "// @grant        GM.getValue",
  "// @grant        GM.setValue",
  `// @updateURL    ${raw}`,
  `// @downloadURL  ${raw}`,
  "// ==/UserScript==",
  ""
].join("\n");

const body = [
  `const SETTINGS_HTML = ${JSON.stringify(settingsHtml)};`,
  `const BLOCKED_HTML = ${JSON.stringify(blockedHtml)};`,
  read(here, "platform.js"),
  read(ext, "src/filters.js"),
  read(ext, "src/policy.js"),
  read(ext, "src/sites.js"),
  read(ext, "src/content.js")
].join("\n;\n");

const out = path.join(here, "safescroll.user.js");
fs.writeFileSync(out, `${header}\n// Generated by userscript/build.mjs from extension/ — edit those files, not this one.\n(async () => {\n${body}\n})();\n`);
console.log(`Wrote ${path.relative(process.cwd(), out)} (${Math.round(fs.statSync(out).size / 1024)} KB, v${version})`);
